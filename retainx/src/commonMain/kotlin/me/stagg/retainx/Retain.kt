/**
 * Retains the value produced by [calculation] under the explicit [key].
 *
 * @param inputs A set of inputs that reset the retained value when any of them change.
 * @param key The key used to identify the retained value.
 * @param calculation A factory that creates the retained value.
 */
@Composable
@NonRestartableComposable
public fun <T : Any> retain(
  vararg inputs: Any?,
  key: String,
  calculation: () -> T,
): T {
  require(key.isNotEmpty()) { "Retained key is empty" }
  return retainInternal(
    inputs = inputs,
    key = key,
    saver = neverSave(),
    init = calculation,
  )
}

/**
 * Retains the value produced by [calculation] and opportunistically saves it with [saver].
 *
 * @param inputs A set of inputs that reset the retained value when any of them change.
 * @param saver Defines how the value is saved and restored.
 * @param key An optional explicit identity for the retained and saved value.
 * @param calculation A factory that creates the value when neither retained nor saved state exists.
 */
@Composable
@NonRestartableComposable
public fun <T : Any> retainSaveable(
  vararg inputs: Any?,
  saver: Saver<T, out Any> = autoSaver(),
  key: String? = null,
  calculation: () -> T,
): T = retainInternal(inputs = inputs, saver = saver, key = key, init = calculation)

@Composable
internal fun <T : Any> retainInternal(
  vararg inputs: Any?,
  saver: Saver<T, out Any>,
  key: String? = null,
  init: () -> T,
): T {
  val saveableStateRegistry = LocalSaveableStateRegistry.current
  val retainedValuesStore = LocalRetainedValuesStore.current
  // key is the one provided by the user or the one generated by the compose runtime
  val finalKey =
    if (!key.isNullOrEmpty()) {
      key
    } else {
      currentCompositeKeyHashCode.toString(MaxSupportedRadix)
    }

  @Suppress("UNCHECKED_CAST") (saver as Saver<T, Any>)

  val holder = remember {
    // value is restored using the retained store first, the saveable registry second, or
    // created via [init] lambda third. Both are consumed so neither leaks a stale entry.
    @Suppress("UNCHECKED_CAST")
    val retainedRestored =
      retainedValuesStore.consumeExitedValueOrDefault(RetainSaveableKey(finalKey), null)
        as? RetainableSaveableHolder.Value<T>
    val saveableRestored =
      saveableStateRegistry?.consumeRestored(finalKey)?.let { saver.restore(it) }
    val retainedMatches = retainedRestored != null && retainedRestored.inputs.contentEquals(inputs)
    val finalValue =
      when {
        retainedMatches -> retainedRestored.value
        retainedRestored != null -> {
          // Retained with different inputs: it's been taken out of the store and won't be used.
          retainedRestored.onRetired()
          init()
        }
        else -> saveableRestored ?: init()
      }
    RetainableSaveableHolder(
      retainedValuesStore = retainedValuesStore,
      saveableStateRegistry = saveableStateRegistry,
      saver = saver,
      key = finalKey,
      value = finalValue,
      inputs = inputs,
      hasBeenRestoredFromRetained = retainedMatches,
    )
  }
  val value = holder.getValueIfInputsAreEqual(inputs) ?: init()
  SideEffect {
    holder.update(
      retainedValuesStore = retainedValuesStore,
      saveableStateRegistry = saveableStateRegistry,
      saver = saver,
      key = finalKey,
      value = value,
      inputs = inputs,
    )
  }
  return value
}

/**
 * Retains a [MutableState] produced by [calculation] and opportunistically saves its value with
 * [stateSaver].
 */
@Composable
@NonRestartableComposable
public fun <T> retainSaveable(
  vararg inputs: Any?,
  stateSaver: Saver<T, out Any>,
  key: String? = null,
  calculation: () -> MutableState<T>,
): MutableState<T> =
  retainSaveable(
    *inputs,
    saver = mutableStateSaver(stateSaver),
    key = key,
    calculation = calculation,
  )

/** The maximum radix available for conversion to and from strings. */
private const val MaxSupportedRadix = 36

private val NoOpSaver = Saver<Any?, Any>({ null }, { null })

@Suppress("UNCHECKED_CAST")
private fun <Original, Saveable : Any> neverSave() = NoOpSaver as Saver<Original, Saveable>

/** Namespaces [retainSaveable] keys in a [RetainedValuesStore] shared with other callers. */
private data class RetainSaveableKey(val key: String)

/**
 * Keeps a value in the [RetainedValuesStore] across composition exit and opportunistically saves it
 * to the [SaveableStateRegistry] so it can still be restored when retained values are lost (e.g.
 * process death or a [ForgetfulRetainedValuesStore]). Both write out the same current [value].
 */
private class RetainableSaveableHolder<T : Any>(
  private var retainedValuesStore: RetainedValuesStore,
  private var saveableStateRegistry: SaveableStateRegistry?,
  private var saver: Saver<T, Any>,
  private var key: String,
  private var value: T,
  private var inputs: Array<out Any?>,
  private val hasBeenRestoredFromRetained: Boolean = false,
) : RememberObserver, SaverScope {
  private var saveableStateEntry: SaveableStateRegistry.Entry? = null

  /** Value provider called by the saveable registry. */
  private val valueProvider = { with(saver) { save(value) } }

  fun update(
    retainedValuesStore: RetainedValuesStore,
    saveableStateRegistry: SaveableStateRegistry?,
    saver: Saver<T, Any>,
    key: String,
    value: T,
    inputs: Array<out Any?>,
  ) {
    var saveableEntryIsOutdated = false
    // The retained store is only written on exit, so swapping it or the key needs no
    // re-registration
    this.retainedValuesStore = retainedValuesStore
    if (this.saveableStateRegistry !== saveableStateRegistry) {
      this.saveableStateRegistry = saveableStateRegistry
      saveableEntryIsOutdated = true
    }
    if (this.key != key) {
      this.key = key
      saveableEntryIsOutdated = true
    }
    val previous = this.value
    this.saver = saver
    this.value = value
    this.inputs = inputs
    if (previous !== value) {
      // Inputs changed: the previous value leaves for good and the new one takes its place
      if (previous is RetainObserver) {
        previous.onExitedComposition()
        previous.onRetired()
      }
      if (value is RetainObserver) {
        value.onRetained()
        value.onEnteredComposition()
      }
    }
    if (saveableStateRegistry != null && saveableEntryIsOutdated) {
      saveableStateEntry?.unregister()
      saveableStateEntry = null
      registerSaveable()
    }
  }

  private fun registerSaveable() {
    val registry = saveableStateRegistry ?: return
    require(saveableStateEntry == null) { "entry($saveableStateEntry) is not null" }
    registry.requireCanBeSaved(valueProvider())
    saveableStateEntry = registry.registerProvider(key, valueProvider)
  }

  override fun canBeSaved(value: Any): Boolean {
    val registry = saveableStateRegistry
    return registry == null || registry.canBeSaved(value)
  }

  override fun onRemembered() {
    registerSaveable()
    val v = value
    if (v is RetainObserver) {
      // Values restored from the retained store were already retained
      if (!hasBeenRestoredFromRetained) v.onRetained()
      v.onEnteredComposition()
    }
  }

  override fun onForgotten() {
    saveableStateEntry?.unregister()
    saveableStateEntry = null
    val v = value
    if (v is RetainObserver) v.onExitedComposition()
    // The store decides whether to keep the value or retire it.
    retainedValuesStore.saveExitingValue(RetainSaveableKey(key), Value(v, inputs))
  }

  override fun onAbandoned() {
    val v = value
    if (v is RetainObserver) v.onUnused()
  }

  fun getValueIfInputsAreEqual(inputs: Array<out Any?>): T? {
    return value.takeIf { inputs.contentEquals(this.inputs) }
  }

  /**
   * What's kept in the [RetainedValuesStore]: the value and the inputs it was created with.
   * Forwards [onRetired] so the store can retire the wrapped value.
   */
  class Value<T>(val value: T, val inputs: Array<out Any?>) : RetainObserver {
    override fun onRetained() {}

    override fun onEnteredComposition() {}

    override fun onExitedComposition() {}

    override fun onRetired() {
      val v = value
      if (v is RetainObserver) v.onRetired()
    }

    override fun onUnused() {}
  }
}

private fun SaveableStateRegistry.requireCanBeSaved(value: Any?) {
  require(value == null || canBeSaved(value)) {
    if (value is SnapshotMutableState<*>) {
      if (
        value.policy !== neverEqualPolicy<Any?>() &&
          value.policy !== structuralEqualityPolicy<Any?>() &&
          value.policy !== referentialEqualityPolicy<Any?>()
      ) {
        "If you use a custom SnapshotMutationPolicy for your MutableState you have to" +
          " write a custom Saver"
      } else {
        "MutableState containing ${value.value} cannot be saved using the current " +
          "SaveableStateRegistry. The default implementation only supports types " +
          "which can be stored inside the Bundle. Please consider implementing a " +
          "custom Saver for this class and pass it as a stateSaver parameter to " +
          "retainSaveable()."
      }
    } else {
      "$value cannot be saved using the current SaveableStateRegistry. The default " +
        "implementation only supports types which can be stored inside the Bundle" +
        ". Please consider implementing a custom Saver for this class and pass it" +
        " to retainSaveable()."
    }
  }
}

@Suppress("UNCHECKED_CAST")
private fun <T> mutableStateSaver(inner: Saver<T, out Any>) =
  with(inner as Saver<T, Any>) {
    Saver<MutableState<T>, MutableState<Any?>>(
      save = { state ->
        require(state is SnapshotMutableState<T>) {
          "If you use a custom MutableState implementation you have to write a custom " +
            "Saver and pass it as a saver param to retainSaveable()"
        }
        val saved = save(state.value)
        if (saved != null) {
          mutableStateOf(saved, state.policy as SnapshotMutationPolicy<Any?>)
        } else {
          // if the inner saver returned null we need to return null as well so the
          // user's init lambda will be used instead of restoring mutableStateOf(null)
          null
        }
      },
      restore =
        @Suppress("UNCHECKED_CAST", "ExceptionMessage") {
          require(it is SnapshotMutableState<Any?>)
          mutableStateOf(
            if (it.value != null) restore(it.value!!) else null,
            it.policy as SnapshotMutationPolicy<T?>,
          )
            as MutableState<T>
        },
    )
  }
